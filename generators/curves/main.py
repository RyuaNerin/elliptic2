def generate_curves(
    catalog: CurveCatalog,
    env: Environment,
) -> None:
    workspace_dir: Final = Path("..", "..")

    internal_dir: Final = workspace_dir / "internal" / "curves"
    internal_dir.mkdir(parents=True, exist_ok=True)

    definitions_by_namespace: dict[str, list[CurveEntry]] = {}
    for definition in catalog.canonical_by_key.values():
        definitions_by_namespace.setdefault(
            definition.namespace["namespace"], []
        ).append(definition)

    aliases_by_namespace: dict[str, list[CurveEntry]] = {}
    for variant in catalog.variants:
        if variant is catalog.canonical_by_key[variant.parameter_key]:
            continue
        aliases_by_namespace.setdefault(variant.namespace["namespace"], []).append(
            variant
        )

    namespaces = sorted(set(definitions_by_namespace) | set(aliases_by_namespace))
    expected = {"alias.go", "oid.go", "oid_test.go"}
    expected.update(f"{namespace}.go" for namespace in namespaces)
    expected.update(
        f"{namespace}_test.go"
        for namespace, entries in definitions_by_namespace.items()
        if entries
    )
    for path in internal_dir.glob("*.go"):
        if path.name not in expected:
            remove_generated(path)

    oid_context = internal_oid_context(catalog)
    write_template(
        internal_dir / "oids" / "oids.go",
        env,
        "internal/curves/oids/oids.go.j2",
        oid_context,
    )
    write_template(
        workspace_dir / "oids" / "oid.go",
        env,
        "oids/oid.go.j2",
        oid_context,
    )
    write_template(
        workspace_dir / "oids" / "oid_test.go",
        env,
        "oids/oid_test.go.j2",
        oid_context,
    )

    for namespace in namespaces:
        definitions = definitions_by_namespace.get(namespace, [])
        aliases = aliases_by_namespace.get(namespace, [])
        write_template(
            internal_dir / f"{namespace}.go",
            env,
            "internal/curves/namespace.go.j2",
            internal_namespace_context(namespace, definitions, aliases, catalog),
        )
        if definitions:
            write_template(
                internal_dir / f"{namespace}_test.go",
                env,
                "internal/curves/namespace_test.go.j2",
                internal_test_context(namespace, definitions),
            )


def internal_oid_context(catalog: CurveCatalog) -> dict[str, Any]:
    oid_entries: list[dict[str, Any]] = []
    entries_by_oid: dict[str, CurveEntry] = {}

    for entry in catalog.variants:
        oid = cast(str | None, entry.curve["unified_curve"]["params"].get("oid"))
        if oid is None:
            continue

        previous = entries_by_oid.get(oid)
        if previous is not None:
            raise ValueError(
                f"Duplicate OID {oid}: {previous.fullname} and {entry.fullname}"
            )
        entries_by_oid[oid] = entry

        try:
            oid_arcs = [str(int(arc)) for arc in oid.split(".")]
        except ValueError as ex:
            raise ValueError(f"Invalid OID {oid}: {entry.fullname}") from ex

        oid_entries.append(
            {
                "golang_var": f"OID{entry.internal_name}",
                "golang_fun": entry.internal_name,
                "oid": oid,
                "oid_arcs": oid_arcs,
            }
        )

    return {
        "oid_entries": sorted(oid_entries, key=lambda item: item["golang_var"]),
    }


def alias_test_context(catalog: CurveCatalog) -> dict[str, Any]:
    families: list[list[AliasTestCurve]] = []
    namespaces: set[str] = set()

    for family in catalog.families:
        test_curves: list[AliasTestCurve] = []
        for entry in family:
            oid = cast(
                str | None,
                entry.curve["unified_curve"]["params"].get("oid"),
            )
            test_curves.append(
                {
                    "name": entry.fullname,
                    "curve_expr": (
                        f"{entry.namespace['namespace']}.{entry.curve['golang_fun']}()"
                    ),
                    "oid": oid or "",
                }
            )

            if std_curve := GO_STD_CURVES.get(entry.fullname):
                test_curves.append(
                    {
                        "name": f"crypto/elliptic.{std_curve[0]}",
                        "curve_expr": f"elliptic.{std_curve[0]}()",
                        "oid": std_curve[1],
                    }
                )

        if len(test_curves) > 1:
            families.append(test_curves)
            namespaces.update(entry.namespace["namespace"] for entry in family)

    return {
        "families": families,
        "namespaces": sorted(namespaces),
    }


def generate_testcase(
    namespace: str,
    curve: UnifiedCurve,
    rm: bool,
) -> tuple[str, GeneratedTestCases | None]:

    tmpdir = CACHE_DIR / namespace / curve["name"].replace("/", "_")
    input_json = Path(tmpdir) / "curve.json"
    output_dir = Path(tmpdir) / "output"

    error_file = output_dir / "error.txt"
    result_file = output_dir / "result.json"

    output_dir.mkdir(parents=True, exist_ok=True)

    if error_file.exists():
        error_file.unlink()

    with input_json.open("w", encoding="utf-8") as fs:
        json.dump(curve, fs, indent=2)

    local_dir = Path(".")
    volumes: dict[str, dict[str, str]] = {
        str((local_dir / file.name).absolute()): {
            "bind": f"/input/{file.name}",
            "mode": "ro",
        }
        for file in local_dir.iterdir()
        if file.is_file() and file.suffix == ".py"
    }
    volumes[str(input_json.absolute())] = {"bind": "/input/curve.json", "mode": "ro"}
    volumes[str(output_dir.absolute())] = {"bind": "/output", "mode": "rw"}

    # Docker 컨테이너 실행
    docker_cli: Any = None
    docker_container: Any = None
    try:
        docker_cli = docker.client.DockerClient()

        docker_name = f"ryuanerin-elliptic2-sagegen-{curve['type'].lower()}-{namespace}-{curve['name'].replace('/', '_')}"
        docker_name = reDockerInvalidChar.sub("_", docker_name)

        try:
            docker_cli.containers.get(docker_name).remove(force=True)
        except docker.errors.NotFound:
            pass  # 컨테이너가 존재하지 않으면 무시

        docker_container = docker_cli.containers.run(
            name=docker_name,
            image=SAGEMATH_DOCKER_IMAGE,
            command=["sage", f"/input/{SAGE_FILE}"],
            volumes=volumes,
            cpu_count=1,
            remove=rm,
            detach=True,
        )
        docker_container.wait(timeout=300)

        # 결과 파일 읽기
        if error_file.exists():
            with error_file.open("r", encoding="utf-8") as fs:
                error_msg = fs.read()
            raise RuntimeError(f"SageMath error for {curve['name']}: {error_msg}")

        if not result_file.exists():
            raise RuntimeError(f"Output file not generated for {curve['name']}")

        with result_file.open("r", encoding="utf-8") as fs:
            return curve["name"], json.load(fs)

        # docker_container.stop()
        # docker_container.remove()

    except Exception as ex:  # noqa: BLE001
        print(f"Error generating test case for {namespace} - {curve['name']}: {ex}")
        return curve["name"], None

    finally:
        if docker_cli is not None:
            docker_cli.close()


def unify_document(std: dict[str, GitDocument]) -> list[UnifiedNamespace]:
    ret: list[UnifiedNamespace] = []

    def to_int(x: int | str | GitRaw | None) -> int:
        if x is None:
            raise ValueError("Input cannot be None")
        if isinstance(x, int):
            return x
        if isinstance(x, str):
            if x.startswith("0x"):
                return int(x, 16)
            if x.startswith("-0x"):
                return -int(x[3:], 16)
            return int(x)
        return to_int(x.get("raw", None))

    def to_nullable(x: int | str | GitRaw | None) -> int | None:
        if x is None:
            return None
        if isinstance(x, int):
            return x
        if isinstance(x, str):
            if x.startswith("0x"):
                return int(x, 16)
            if x.startswith("-0x"):
                return -int(x[3:], 16)
            return int(x)
        return to_nullable(x.get("raw", None))

    for namespace, doc in std.items():
        curve_list: list[UnifiedCurve] = []
        ignored_curve_list: list[IgnoredCurve] = []

        def append_ignored_curve(
            curve: GitCurve,
            curve_type: CurveTypes | None,
            reason: str,
            *,
            _target: list[IgnoredCurve] = ignored_curve_list,
        ):
            _target.append(
                {
                    "name": curve["name"],
                    "desc": curve["desc"],
                    "type": curve_type.value if curve_type else "unknown",
                    "aliases": curve.get("aliases") or [],
                    "raw": curve,
                    "reason": reason,
                }
            )

        for std_curve in doc["curves"]:
            try:
                curve_type = CurveTypes.get(std_curve)
            except UnsupportedCurveTypeError as e:
                print(
                    f"Skipping curve {std_curve['name']} in {namespace} due to unsupported type: {e.message}"
                )
                append_ignored_curve(std_curve, None, e.message)
                continue

            a = to_nullable(std_curve.get("params", {}).get("a", None))
            b = to_nullable(std_curve.get("params", {}).get("b", None))
            c = to_nullable(std_curve.get("params", {}).get("c", None))
            d = to_nullable(std_curve.get("params", {}).get("d", None))
            gx = to_nullable((std_curve.get("generator", None) or {}).get("x", None))
            gy = to_nullable((std_curve.get("generator", None) or {}).get("y", None))
            h = to_int(std_curve["cofactor"])
            n = to_int(std_curve["order"])

            """
            if gx is None or gy is None:
                print(
                    f"Skipping curve {std_curve['name']} in {namespace} due to missing generator point"
                )
                append_ignored_curve(std_curve, "has no generator point")
                continue
            """
            if gx is not None and gy is None:
                print(
                    f"Skipping curve {std_curve['name']} in {namespace} due to missing Gy coordinate"
                )
                append_ignored_curve(
                    std_curve, curve_type, "has no generator y coordinate"
                )
                continue
            if gy is not None and gx is None:
                print(
                    f"Skipping curve {std_curve['name']} in {namespace} due to missing Gx coordinate"
                )
                append_ignored_curve(
                    std_curve, curve_type, "has no generator x coordinate"
                )
                continue

            aliases = std_curve.get("aliases") or []

            uc: UnifiedCurve = {
                "type": curve_type.value,
                "name": std_curve["name"],
                "desc": std_curve["desc"],
                "aliases": aliases,
                "raw": std_curve,
                "params": {
                    "n": n,
                },
            }
            oid = std_curve.get("oid", None)
            match curve_type:
                case CurveTypes.WEIERSTRASS_BINARY_POLY:
                    field = cast(GitFieldBinaryPoly, std_curve["field"])
                    cwb: WeierstrassBinaryCurveParams = {
                        "bits": to_int(field["bits"]),
                        "fx": [to_int(poly["power"]) for poly in field["poly"]],
                        "a2": a or 0,
                        "a6": b or 0,
                        "gx": gx,
                        "gy": gy,
                        "h": h,
                        "n": n,
                        "oid": oid,
                    }
                    uc["params"] = cwb

                case CurveTypes.WEIERSTRASS_PRIME:
                    field = cast(GitFieldPrime, std_curve["field"])
                    cwp: WeierstrassPrimeCurveParams = {
                        "bits": to_int(field["bits"]),
                        "p": to_int(field["p"]),
                        "a": a or 0,
                        "b": b or 0,
                        "gx": gx,
                        "gy": gy,
                        "h": h,
                        "n": n,
                        "oid": oid,
                    }
                    uc["params"] = cwp

                case CurveTypes.MONTGOMERY_PRIME:
                    field = cast(GitFieldPrime, std_curve["field"])
                    cm: MontgomeryCurveParams = {
                        "bits": to_int(field["bits"]),
                        "p": to_int(field["p"]),
                        "a": a or 0,
                        "b": b or 0,
                        "gx": gx,
                        "gy": gy,
                        "h": h,
                        "n": n,
                        "oid": oid,
                    }
                    uc["params"] = cm

                case CurveTypes.TWISTEDEDWARDS_PRIME:
                    field = cast(GitFieldPrime, std_curve["field"])
                    cte: TwistedEdwardsCurveParams = {
                        "bits": to_int(field["bits"]),
                        "p": to_int(field["p"]),
                        "a": a or 0,
                        "d": d or 0,
                        "gx": gx,
                        "gy": gy,
                        "h": h,
                        "n": n,
                        "oid": oid,
                    }
                    uc["params"] = cte

                case CurveTypes.EDWARDS_PRIME:
                    field = cast(GitFieldPrime, std_curve["field"])
                    ce: EdwardsCurveParams = {
                        "bits": to_int(field["bits"]),
                        "p": to_int(field["p"]),
                        "c": c or 0,
                        "d": d or 0,
                        "gx": gx,
                        "gy": gy,
                        "h": h,
                        "n": n,
                        "oid": oid,
                    }
                    uc["params"] = ce

            curve_list.append(uc)

        curve_list.sort(key=lambda x: x["name"].lower())
        ignored_curve_list.sort(key=lambda x: x["name"].lower())

        ns: UnifiedNamespace = {
            "name": doc["name"],
            "namespace": namespace,
            "desc": doc["desc"],
            "curve_list": curve_list,
            "ignored_curve_list": ignored_curve_list,
        }
        ret.append(ns)

    ret.sort(key=lambda x: (x["name"] == "other", x["name"]))

    return ret


def read_std_curves(
    git_dir: Path,
    repo_url: str,
    *,
    update: bool = True,
) -> dict[str, GitDocument]:
    std: dict[str, GitDocument] = {}

    if not (git_dir / ".git").exists():
        repo = Repo.clone_from(
            url=repo_url,
            to_path=git_dir,
        )
        repo.git.checkout("data")
    elif update:
        repo = Repo(git_dir)
        repo.git.checkout("data")
        repo.remotes.origin.pull()

    for dir in git_dir.iterdir():
        if not dir.is_dir():
            continue

        curves_json = dir / "curves.json"

        if curves_json.exists():
            print(f"Processing {curves_json}")

            with curves_json.open("r", encoding="utf-8") as fs:
                std[dir.name] = json.load(fs)

    return std


