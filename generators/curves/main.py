def capitalize(s: str) -> str:
    if len(s) == 0:
        return ""
    if len(s) == 1:
        return s.upper()
    return s[0].upper() + s[1:]


def to_golang_function_name(namespace: str, name: str) -> str:
    # 숫자로 시작하는 경우 namespace 접두사 추가
    if re.match(r"^\d", name):
        name = capitalize_part(namespace) + name

    # 슬래시 -> 언더스코어
    name = name.replace("/", "_")

    # 숫자-숫자 -> 숫자_숫자
    name = re.sub(r"(\d)-(\d)", r"\1_\2", name)

    # 하이픈, 공백 기준으로 분리 후 PascalCase 변환
    parts = re.split(r"[-\s]+", name)
    name = "".join(capitalize_part(part) for part in parts if part)

    # 영문자/숫자/언더스코어 외 문자 제거
    name = re.sub(r"[^a-zA-Z0-9_]", "", name)

    # print(oname, "->", name)
    return name


def noncapitalize_part(s: str) -> str:
    """첫 글자만 소문자 보장, 나머지 원본 유지."""
    if not s:
        return s
    return s[0].lower() + s[1:]


def capitalize_part(s: str) -> str:
    """첫 글자만 대문자 보장, 나머지 원본 유지."""
    if not s:
        return s
    return s[0].upper() + s[1:]


