from typing import Final

GO_ARCH_64: Final = [
    "amd64",
    "arm64",
    "ppc64",
    "ppc64le",
    "mips64",
    "mips64le",
    "riscv64",
    "s390x",
    "loong64",
    "sparc64",
    "wasm",
]
GO_ARCH_32: Final = [
    "386",
    "arm",
    "mips",
    "mipsle",
]
GENERATED: Final = "// Code generated by generator.py. DO NOT EDIT."


def _require(cond: bool, msg: str) -> None:
    if not cond:
        raise ValueError(msg)


def validate_poly(m: int, poly_bits: list[int], word_bits: int) -> None:
    _require(len(poly_bits) >= 2, f"{poly_bits}: require at least 2 terms")
    _require(
        poly_bits == sorted(set(poly_bits), reverse=True),
        f"{poly_bits}: require unique and descending order",
    )
    _require(poly_bits[0] == m, f"{poly_bits}: require the highest term to be m={m}")
    _require(poly_bits[-1] >= 0, f"{poly_bits}: require non-negative bits")
    _require(m < 65536, f"m={m}: require less than 65536 (hash constraint)")
    _require(
        poly_bits[1] + word_bits <= m,
        f"m={m}, {poly_bits}: require single-pass reduction with {word_bits}-bit words",
    )


def _xor_lines(src: str, targets: dict[int, list[int]]) -> list[str]:
    lines = []
    for tw in sorted(targets):
        shifts = sorted(targets[tw], key=lambda s: s < 0)
        # >0: <<
        # =0: same
        # <0: >>
        parts = [
            src if s == 0 else f"({src} << {s})" if s > 0 else f"({src} >> {-s})"
            for s in shifts
        ]
        lines.append(f"\tr{tw} ^= " + " ^ ".join(parts))
    return lines


def base_name(m: int, poly_bits: list[int]) -> str:
    return f"Reduce{m}_" + "_".join(map(str, poly_bits))


def generate_reduce_function(
    m: int,
    poly_bits: list[int],
    word_bits: int = 64,
    word_type: str = "big.Word",
    fun_name: str | None = None,
) -> tuple[str, str]:
    validate_poly(m, poly_bits, word_bits)

    # x^m 제외
    reduction_bits = poly_bits[1:]

    # 워드 수 계산
    n_words = (m + word_bits - 1) // word_bits
    m_word_idx, m_bit_idx = divmod(m, word_bits)

    k = len(reduction_bits)
    poly_type = {2: "trinomial", 4: "pentanomial"}.get(k, f"{k + 1}-nomial")
    fun_name = fun_name or base_name(m, poly_bits)

    lines = [
        f"// GF(2^{m}) fast reduction",
        f"// f(x) = x^{m} + "
        + " + ".join(f"x^{b}" if b > 0 else "1" for b in reduction_bits),
        f"// Type: {poly_type}",
        f"// n = {n_words} words, m_word_idx = {m_word_idx}, m_bit_idx = {m_bit_idx}",
        f"func {fun_name}(result []{word_type}, prod []{word_type}) {{",
        f"\t_ = result[{n_words - 1}]",
        f"\t_ = prod[{2 * n_words - 1}]",
        f"\tclear(result[{n_words}:])",
        "",
    ]

    lines += [f"\tr{i} := prod[{i}]" for i in range(2 * n_words)]
    lines.append("")

    # 전체 워드 reduction (m_bit_idx == 0이면 m_word_idx == n 까지 포함)
    for i in range(2 * n_words - 1, n_words - 1, -1):
        base_shift = i * word_bits - m
        lines.append(
            f"\t// r{i} reduction (bits {i * word_bits}-{(i + 1) * word_bits - 1}), baseShift = {base_shift}"
        )

        targets: dict[int, list[int]] = {}
        for poly_bit in reduction_bits:
            tw, bs = divmod(base_shift + poly_bit, word_bits)
            _require(tw < i, f"{fun_name}: r{i}이 r{tw}로 reduction됨")
            targets.setdefault(tw, []).append(bs)
            if bs > 0:
                _require(tw + 1 < i, f"{fun_name}: r{i} overflow가 r{tw + 1}로 넘침")
                targets.setdefault(tw + 1, []).append(-(word_bits - bs))

        lines += _xor_lines(f"r{i}", targets)
        lines.append("")

    # m_word_idx 상위 비트 처리
    if m_bit_idx > 0:
        lines.append(
            f"\t// r{m_word_idx} upper bits (bits {m}-{(m_word_idx + 1) * word_bits - 1})"
        )
        lines.append(f"\tt := r{m_word_idx} >> {m_bit_idx}")

        t_max_bits = word_bits - m_bit_idx
        targets = {}
        for poly_bit in reduction_bits:
            tw, bs = divmod(poly_bit, word_bits)
            targets.setdefault(tw, []).append(bs)
            if bs > 0 and bs + t_max_bits > word_bits:
                _require(
                    tw + 1 <= m_word_idx, f"{fun_name}: t overflow가 r{tw + 1}로 넘침"
                )
                targets.setdefault(tw + 1, []).append(-(word_bits - bs))

        lines += _xor_lines("t", targets)
        lines.append(f"\tr{m_word_idx} &= 0x{(1 << m_bit_idx) - 1:X}")
        lines.append("")

    lines += [f"\tresult[{i}] = r{i}" for i in range(n_words)]
    lines += ["}", ""]

    return fun_name, "\n".join(lines)


def _go_ints(bits: list[int]) -> str:
    return "[]int{" + ", ".join(map(str, bits)) + "}"


def render_table(entries: list[tuple[list[int], str]]) -> list[str]:
    lines = [
        GENERATED,
        "",
        "package gf2mreduce",
        'import "slices"',
        "func lookupReduce(polyBits []int) ReduceFunc {",
        "switch {",
    ]
    for bits, name in entries:
        lines += [
            f"case slices.Equal(polyBits, {_go_ints(bits)}):",
            f"return {name}",
        ]
    lines += [
        "   }",
        "   return nil",
        "}",
        "",
        "var reduces = [][]int{",
    ]
    lines += [f"{{{', '.join(map(str, bits))}}}," for bits, _ in entries]
    lines += ["}"]
    return lines


# generic 경로 전용 테스트 다항식 (single-pass 불가, 워드 경계, 작은 m, 큰 m 포함)
GENERIC_TEST_POLIES: Final = [
    [1, 0],
    [7, 6, 0],
    [32, 31, 0],
    [64, 4, 3, 1, 0],
    [100, 99, 0],
    [128, 127, 0],
    [200, 199, 150, 1, 0],
    [1000, 999, 3, 0],
]


def render_test(polies: list[tuple[int, list[int]]], names: list[str]) -> str:
    cases = "\n".join(
        f"\t{{{_go_ints(bits)}, {name}}}," for (_, bits), name in zip(polies, names)
    )
    generic = "\n".join(f"\t{_go_ints(bits)}," for bits in GENERIC_TEST_POLIES)
    return f"""{GENERATED}
 
package gf2mreduce
 
import (
	"math/big"
	"math/bits"
	"math/rand/v2"
	"slices"
	"testing"
 
	"github.com/stretchr/testify/require"
)
 
var generatedReduceCases = []struct {{
	poly []int
	fn   ReduceFunc
}}{{
{cases}
}}
 
var genericReducePolies = [][]int{{
{generic}
}}
 
func naiveReduce(prod []big.Word, poly []int) []big.Word {{
	const W = bits.UintSize
	m := poly[0]
	r := slices.Clone(prod)
	for d := len(r)*W - 1; d >= m; d-- {{
		if r[d/W]>>uint(d%W)&1 == 0 {{
			continue
		}}
		for _, p := range poly {{
			e := d - m + p
			r[e/W] ^= 1 << uint(e%W)
		}}
	}}
	return r[:(m+W-1)/W]
}}
 
func checkReduce(t *testing.T, poly []int, fn ReduceFunc) {{
	t.Helper()
	const W = bits.UintSize
	rng := rand.New(rand.NewPCG(1, 2))
	n := (poly[0] + W - 1) / W
	for iter := range 2000 {{
		prod := make([]big.Word, 2*n)
		for i := range prod {{
			switch iter {{
			case 0:
				prod[i] = 0
			case 1:
				prod[i] = ^big.Word(0)
			default:
				prod[i] = big.Word(rng.Uint64())
			}}
		}}
		want := naiveReduce(prod, poly)
 
		result := make([]big.Word, n+2)
		for i := range result {{
			result[i] = ^big.Word(0)
		}}
		in := slices.Clone(prod)
		fn(result, in)
 
		require.Equal(t, want, result[:n], "%v: prod=%x", poly, prod)
		require.Equal(t, make([]big.Word, len(result)-n), result[n:], "%v: result[%d:] not cleared", poly, n)
		require.Equal(t, prod, in, "%v: prod modified", poly)
	}}
}}
 
func TestGeneratedReduce(t *testing.T) {{
	for _, tc := range generatedReduceCases {{
		checkReduce(t, tc.poly, tc.fn)
	}}
}}
 
func TestLookupReduce(t *testing.T) {{
	for _, tc := range generatedReduceCases {{
		require.NotNil(t, lookupReduce(tc.poly), "%v: not found", tc.poly)
	}}
	for _, poly := range genericReducePolies {{
		require.Nil(t, lookupReduce(poly), "%v: unexpectedly found", poly)
	}}
}}
 
func TestGenericReduce(t *testing.T) {{
	for _, tc := range generatedReduceCases {{
		checkReduce(t, tc.poly, newGenericReduce(tc.poly))
	}}
	for _, poly := range genericReducePolies {{
		checkReduce(t, poly, GetReduceFunction(poly))
	}}
}}
 
func TestGenericReduceInvalid(t *testing.T) {{
	for _, poly := range [][]int{{nil, {{5}}, {{5, 5, 0}}, {{5, 0, 3}}, {{5, 3, -1}}}} {{
		require.Panics(t, func() {{ GetReduceFunction(poly) }}, "%v", poly)
	}}
}}
"""


def run_gofmt(paths: list[str]) -> None:
    gofmt = shutil.which("gofmt")
    if gofmt is None:
        return
    subprocess.run([gofmt, "-w", *paths], check=True)


def render_dispatcher(name: str) -> str:
    impl = name[0].lower() + name[1:]
    return f"""// {name} dispatches by bits.UintSize.
func {name}(result []big.Word, prod []big.Word) {{
	if bits.UintSize == 64 {{
		{impl}_64bit(as64(result), as64(prod))
	}} else {{
		{impl}_32bit(as32(result), as32(prod))
	}}
}}
"""


GENERIC_PRELUDE: Final = """import (
	"math/big"
	"math/bits"
	"unsafe"
)

func as64(w []big.Word) []uint64 {
	return unsafe.Slice((*uint64)(unsafe.Pointer(unsafe.SliceData(w))), len(w))
}

func as32(w []big.Word) []uint32 {
	return unsafe.Slice((*uint32)(unsafe.Pointer(unsafe.SliceData(w))), len(w))
}
"""


def main(polies: list[tuple[int, list[int]]]) -> None:
    seen: set[tuple[int, ...]] = set()
    entries: list[tuple[list[int], str]] = []
    bodies64: list[str] = []
    bodies32: list[str] = []
    bodies_generic: list[str] = []

    for m, poly_bits in polies:
        name, body64 = generate_reduce_function(m, poly_bits, 64)
        _, body32 = generate_reduce_function(m, poly_bits, 32)

        impl = name[0].lower() + name[1:]
        _, g64 = generate_reduce_function(m, poly_bits, 64, "uint64", f"{impl}_64bit")
        _, g32 = generate_reduce_function(m, poly_bits, 32, "uint32", f"{impl}_32bit")

        _require(
            tuple(poly_bits) not in seen,
            f"hash collision or duplicate: {seen} vs {poly_bits}",
        )
        seen.add(tuple(poly_bits))

        entries.append((poly_bits, name))
        bodies64.append(body64)
        bodies32.append(body32)
        bodies_generic += [render_dispatcher(name), g64, g32]

    def header(tag: str) -> list[str]:
        return [f"//go:build {tag}", "", GENERATED, "", "package gf2mreduce", ""]

    def fixed_prelude(word_bits: int) -> list[str]:
        size_check = "bits.UintSize - 64" if word_bits == 64 else "32 - bits.UintSize"
        return [
            "import (",
            '\t"math/big"',
            '\t"math/bits"',
            ")",
            "",
            f"var _ = uint({size_check})",
        ]

    outputs = {
        "reduce_table.go": render_table(entries),
        "reduce_64bit.go": [
            *header(" || ".join(GO_ARCH_64)),
            *fixed_prelude(64),
            *bodies64,
        ],
        "reduce_32bit.go": [
            *header(" || ".join(GO_ARCH_32)),
            *fixed_prelude(32),
            *bodies32,
        ],
        "reduce_generic.go": [
            *header(f"!({' || '.join(GO_ARCH_64 + GO_ARCH_32)})"),
            GENERIC_PRELUDE,
            *bodies_generic,
        ],
        "reduce_generated_test.go": [
            render_test(polies, [name for _, name in entries])
        ],
    }
    for path, lines in outputs.items():
        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))

    run_gofmt(list(outputs))


